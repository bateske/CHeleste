"""Turn the Celeste cart (assets/celeste.p8) into the sketch's data.

    python tools/p8extract.py [--cart assets/celeste.p8] [--png out/sheet.png]
                              [--emulator Emulator.cs]

Writes Cheleste/src/assets/Cart.{h,cpp}: the sprite sheet's top half
(sprites 0-127, packed like gfx_fb: two pixels a byte, the left one in the
low nibble), the 128x64 map (its lower half is the sheet's lower half in the
cart, PICO-8's shared memory) and the sprite flags. The sound is
tools/p8audio.py's.

--png renders the sheet and the whole map to PNGs (a look at what was read);
--emulator checks the map and flags against the copies in NoelFB/Celeste's
Source/PICO-8/Emulator.cs (MapData, mask), an independent source.

Deterministic: the same cart gives the same files byte for byte.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "Cheleste" / "src" / "assets"

P8PAL = [0x000000, 0x1D2B53, 0x7E2553, 0x008751, 0xAB5236, 0x5F574F, 0xC2C3C7, 0xFFF1E8,
         0xFF004D, 0xFFA300, 0xFFEC27, 0x00E436, 0x29ADFF, 0x83769C, 0xFF77A8, 0xFFCCAA]


def sections(text):
    """{name: [lines]} for the cart's __name__ sections."""
    out, cur = {}, None
    for line in text.splitlines():
        m = re.fullmatch(r"__(\w+)__", line.strip())
        if m:
            cur = out.setdefault(m.group(1), [])
        elif cur is not None:
            cur.append(line.rstrip())
    return out


def read_cart(path):
    s = sections(Path(path).read_text(encoding="latin-1"))
    gfx = [[int(ch, 16) for ch in row.ljust(128, "0")[:128]] for row in s["gfx"][:128]]
    gfx += [[0] * 128 for _ in range(128 - len(gfx))]
    # The sheet as PICO-8's memory holds it: 64 bytes a row, left pixel low.
    mem = bytearray()
    for row in gfx:
        for x in range(0, 128, 2):
            mem.append(row[x] | (row[x + 1] << 4))
    tiles = bytearray(128 * 64)
    for y, row in enumerate(s["map"][:32]):
        for x in range(128):
            tiles[y * 128 + x] = int(row[2 * x:2 * x + 2] or "0", 16)
    tiles[32 * 128:] = mem[0x1000:0x2000]          # map rows 32-63 share the sheet's lower half
    flags = bytes.fromhex("".join(s["gff"])[:512].ljust(512, "0"))
    return gfx, bytes(mem), bytes(tiles), flags


def c_array(name, data, per=32):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + per]) for i in range(0, len(data), per)]
    return f"const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def write_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")
        return True
    return False


def emit(mem, tiles, flags, cart_name):
    head = f"// GENERATED by tools/p8extract.py from {cart_name}: do not edit.\n"
    pal = ", ".join(f"0x{((c >> 19) & 0x1F) << 11 | ((c >> 10) & 0x3F) << 5 | ((c >> 3) & 0x1F):04X}" for c in P8PAL)
    h = head + """#pragma once
#include <stdint.h>

namespace cart {
// Sprites 0-127: the sheet's top half, 64 bytes a row, two pixels a byte
// (the left one in the low nibble, as gfx_fb packs them).
extern const uint8_t GFX[4096];
// The map, 128x64 tiles, row-major.
extern const uint8_t MAP[8192];
// The sprite flags (fget), one byte a sprite.
extern const uint8_t FLAGS[128];
// The PICO-8 palette, RGB565.
extern const uint16_t PALETTE[16];
}
"""
    cpp = head + '#include "Cart.h"\n\nnamespace cart {\n\n'
    cpp += c_array("GFX", mem[:0x1000]) + "\n" + c_array("MAP", tiles) + "\n" + c_array("FLAGS", flags[:128], 16)
    cpp += f"\nconst uint16_t PALETTE[16] = {{ {pal} }};\n\n}}\n"
    a = write_if_changed(OUT / "Cart.h", h)
    b = write_if_changed(OUT / "Cart.cpp", cpp)
    return emit_sine() or a or b


def emit_sine():
    """A quarter of a sine wave, 257 points in 1/65536ths (the last, 65536,
    is left to Fix.cpp: it does not fit 16 bits)."""
    import math
    vals = [round(math.sin(i / 256 * math.pi / 2) * 65536) for i in range(256)]
    rows = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, 256, 16)]
    text = ("// GENERATED by tools/p8extract.py: do not edit.\n"
            "// sin(i/256 * pi/2) * 65536 for i = 0..255 (Fix.cpp's p8sin/p8cos).\n"
            '#include <stdint.h>\n\nextern const uint16_t SINE_QUARTER[256] = {\n    '
            + ",\n    ".join(rows) + "\n};\n")
    return write_if_changed(OUT / "Sine.cpp", text)


def render(gfx, tiles, png):
    from PIL import Image
    rgb = [((c >> 16) & 255, (c >> 8) & 255, c & 255) for c in P8PAL]
    sheet = Image.new("RGB", (128, 128))
    sheet.putdata([rgb[p] for row in gfx for p in row])
    sheet.save(png)
    m = Image.new("RGB", (1024, 512))
    px = m.load()
    for ty in range(64):
        for tx in range(128):
            t = tiles[ty * 128 + tx]
            if not t:
                continue
            sx, sy = (t % 16) * 8, (t // 16) * 8
            for y in range(8):
                for x in range(8):
                    c = gfx[sy + y][sx + x]
                    if c:
                        px[tx * 8 + x, ty * 8 + y] = rgb[c]
    m.save(str(Path(png).with_name(Path(png).stem + "_map.png")))


def check_emulator(path, tiles, flags):
    src = Path(path).read_text(encoding="utf-8")
    data = re.sub(r"\s+", "", re.search(r'MapData\s*=\s*@"([^"]*)"', src).group(1))
    half = len(data) // 2
    emap = bytes(int(data[i:i + 2] if i < half else data[i + 1] + data[i], 16) for i in range(0, len(data), 2))
    mask = [int(v) for v in re.findall(r"\d+", re.search(r"mask\s*=\s*new byte\[\]\s*\{([^}]*)\}", src).group(1))]
    bad = [i for i in range(min(len(emap), len(tiles))) if emap[i] != tiles[i]]
    # Sprite 78's flags are 0 in every copy of the cart and 2 in Emulator.cs
    # (the C# version draws that one tile in the terrain layer; the cart
    # never draws it). The cart is kept.
    badf = [i for i in range(min(len(mask), 128)) if mask[i] != flags[i] and i != 78]
    print(f"emulator: map {len(emap)} B, {len(bad)} differ; flags {len(mask)}, {len(badf)} differ (78 excepted)")
    return not bad and not badf


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cart", default=str(ROOT / "assets" / "celeste.p8"))
    ap.add_argument("--png")
    ap.add_argument("--emulator")
    a = ap.parse_args(argv)
    gfx, mem, tiles, flags = read_cart(a.cart)
    changed = emit(mem, tiles, flags, Path(a.cart).name)
    print(f"Cart.*: {'written' if changed else 'unchanged'}")
    if a.png:
        render(gfx, tiles, a.png)
    if a.emulator and not check_emulator(a.emulator, tiles, flags):
        sys.exit(1)


if __name__ == "__main__":
    main()
