"""Make a simulator script that plays the whole game, from boot to the summit.

    python tools/ref/playthrough.py [--out Cheleste/tools/scripts/playthrough.txt]

The route is the community's Any% TAS (tools/ref/tas.py downloads it), one
level after another, through the port built exactly as the board runs it
(16.16 numbers, the board's rnd() seed, from the first frame after boot).
Each level's inputs start on the frame the player appears. The TAS was made
on doubles, so a few levels miss on PICO-8's 16.16: for those, the start is
put off a frame or a few (the player stands still) until the route works
again, or else one frame of the route is left out or doubled. The script presses A on the title, then holds each frame's buttons;
the finished script plays the same in the simulator and on the board.
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import compare  # noqa: E402
import tas  # noqa: E402

NAMES = ["LEFT", "RIGHT", "UP", "DOWN", "A", "B"]     # btn(0..5): jump A, dash B (config.h)
TITLE_WAIT = 30


def run(exe, inputs):
    lines, _ = compare.c_trace(exe, inputs, -2, 0)
    return lines


def room_of(line):
    return int(line.split()[1][1:])


def player_frame(lines, room, after):
    for i in range(after, len(lines)):
        if room_of(lines[i]) == room and re.search(r"[|;] 0 ", lines[i]):
            return i
    return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(compare.SKETCH / "tools" / "scripts" / "playthrough.txt"))
    a = ap.parse_args(argv)
    exe = compare.build(True)
    inputs = [0] * TITLE_WAIT + [16] * 3
    notes, starts = [], []
    for level in range(1, 32):
        room = level - 1
        route = tas.tas(level)
        lines = run(exe, inputs + [0] * 120)
        start = player_frame(lines, room, len(inputs) - 1)
        if start is None:
            raise SystemExit(f"level {level}: no player in room {room}")
        base = inputs + [0] * (start - len(inputs))
        starts.append(start)

        def clears(r):
            lines = run(exe, base + r + [0] * 30)
            if room == 30:                          # the summit: the flag shows (sfx 55)
                return any("sfx55" in l for l in lines[len(base):]), lines
            return any(room_of(l) == room + 1 for l in lines[len(base):]), lines

        found, how = None, ""
        for delay in range(0, 101):              # a balloon bobs once in 100 frames
            ok, lines = clears([0] * delay + route)
            if ok:
                found, how = [0] * delay + route, f"+{delay}" if delay else ""
                break
        if found is None:
            # One frame of the route left out or doubled, anywhere.
            for p in range(len(route)):
                for r, what in ((route[:p] + route[p + 1:], "-"), (route[:p + 1] + route[p:], "*")):
                    ok, lines = clears(r)
                    if ok:
                        found, how = r, f"{what}{p}"
                        break
                if found is not None:
                    break
        if found is None:
            raise SystemExit(f"level {level}: the route misses (delays, one frame out or doubled)")
        trial = base + found
        lines = run(exe, trial + [0] * 30)
        if room < 30:
            left = next(i for i in range(len(base), len(lines)) if room_of(lines[i]) == room + 1)
            inputs = trial[:left]
        else:
            inputs = trial + [0] * 150
        notes.append(f"level {level}" + (f" ({how})" if how else ""))
        print(notes[-1], "frame", len(inputs))
    deaths = run(exe, inputs)[-1].split()[2]

    out = [f"# GENERATED by tools/ref/playthrough.py: the whole game, boot to summit, on the Any% TAS route",
           f"# ({len(inputs)} frames, {len(inputs) / 30:.0f} s at 30 fps; {deaths} deaths; levels changed from the TAS"
           + " (+n: started n frames late, -p / *p: frame p left out / doubled): "
           + (", ".join(n for n in notes if "(" in n) or "none") + ")."]
    # A picture of each level as its player appears, and the summit's score at the end.
    marks = {st: [f"snap level{lv:02d}"] for lv, st in enumerate(starts)}
    out += script(inputs, marks) + ["snap summit"]
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{a.out}: {len(inputs)} frames, {deaths}")

    # The README's GIF (`cl gif`): the same run, four clips of it.
    clips = [(0, 60, "01_title"), (starts[0], starts[3], "02_climb"), (starts[21], starts[22], "03_orb"),
             (starts[30], len(inputs), "04_summit")]
    marks = {}
    for a0, a1, name in clips:
        marks.setdefault(a0, []).append("rec start 2")
        marks.setdefault(a1, []).append(f"rec stop {name}")
    gp = Path(a.out).with_name("gameplay.txt")
    head = ["# GENERATED by tools/ref/playthrough.py: the README's GIF (`cl gif`), clips of playthrough.txt's run."]
    gp.write_text("\n".join(head + script(inputs + [0], marks)) + "\n", encoding="utf-8")
    print(f"{gp}: clips {[c[2] for c in clips]}")


def script(inputs, marks):
    """hold/step lines for inputs, with marks[i]'s lines before frame i."""
    out, cur, n = [], None, 0

    def flush():
        if n:
            out.append("hold " + "+".join(NAMES[b] for b in range(6) if cur >> b & 1) if cur else "release")
            out.append(f"step {n}")
    for i, b in enumerate(inputs):
        if i in marks:
            flush()
            n = 0
            out += marks[i]
        if b != cur:
            flush()
            cur, n = b, 0
        n += 1
    flush()
    out.append("release")
    return out


if __name__ == "__main__":
    main()
